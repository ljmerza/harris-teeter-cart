"""Camoufox launch with one persistent profile + one saved fingerprint.

Adapted from lowedepot's retailers/browser.py (see that project's CLAUDE.md
for why): Kroger sites sit behind Akamai like Home Depot, so we present as
one returning shopper rather than a new device each run.
"""

import json
import logging
import os
import shutil
from pathlib import Path

log = logging.getLogger(__name__)


def _camoufox_stamp():
    """Library + browser build. A saved identity is only reused under the same
    pair: a fingerprint generated by one camoufox can fail another's validation."""
    from importlib.metadata import version

    from camoufox.pkgman import INSTALL_DIR

    try:
        browser = (Path(INSTALL_DIR) / "version.json").read_text().strip()
    except OSError:
        browser = "?"
    return f"{version('camoufox')}|{browser}"


def _camoufox_identity(profile_dir):
    """Launch options generated once, saved beside the profile, reused on every
    launch. A new identity also wipes the profile so cookies never move between
    two different fingerprints."""
    from camoufox.utils import launch_options

    ident = Path(f"{profile_dir}.identity.json")
    stamp = _camoufox_stamp()
    opts = None
    try:
        saved = json.loads(ident.read_text())
        if saved.get("stamp") == stamp:
            opts = saved["options"]
    except (OSError, ValueError, KeyError):
        pass
    if opts is None:
        log.info("camoufox: new identity for %s (%s)", profile_dir, stamp)
        opts = launch_options(headless=False, geoip=True, humanize=True)
        # launch_options copies the whole env (credentials included); persist
        # only what camoufox added and merge the live env back in at launch.
        opts["env"] = {k: v for k, v in opts["env"].items() if os.environ.get(k) != v}
        shutil.rmtree(profile_dir, ignore_errors=True)
        ident.parent.mkdir(parents=True, exist_ok=True)
        ident.write_text(json.dumps({"stamp": stamp, "options": opts}))
    return {
        **opts,
        "env": {**os.environ, **opts["env"]},
        "user_data_dir": profile_dir,
        # Firefox rejects Playwright's default viewport.
        "no_viewport": True,
    }


class Browser:
    """Context manager: yields a fresh page in the persistent profile."""

    def __init__(self, profile_dir):
        self.profile_dir = str(profile_dir)
        self._cm = None

    def __enter__(self):
        from camoufox.sync_api import Camoufox

        # Firefox's profile lock outlives an unclean shutdown.
        for lock in ("lock", ".parentlock"):
            try:
                os.unlink(os.path.join(self.profile_dir, lock))
            except OSError:
                pass
        self._cm = Camoufox(
            from_options=_camoufox_identity(self.profile_dir), persistent_context=True
        )
        try:
            ctx = self._cm.__enter__()
            # Not the opening tab: its startup load interrupts the first goto.
            page = ctx.new_page()
            page.set_default_timeout(35000)
            return page
        except BaseException:
            self.__exit__(None, None, None)
            raise

    def __exit__(self, *exc):
        if self._cm is not None:
            try:
                self._cm.__exit__(None, None, None)
            except Exception:  # noqa: BLE001 - best effort on shutdown
                log.warning("camoufox shutdown failed", exc_info=True)
            self._cm = None
        return False
